@needs_package
def test_reproduces_the_packages_own_reference_output():
    """Our scores must equal the ones estimateScore.R produced for its own example.

    sample_input.gct (17,256 genes x 10 samples) -> sample_estimate.gct.
    Tolerance is 1e-6 relative: this is a port, not an approximation.
    """
    raw = _read_gct(_member("inst/extdata/sample_input.gct"))
    reference = _read_gct(_member("inst/extdata/sample_estimate.gct"))
    signatures = load_signatures(ESTIMATE_TARBALL)

    # The reference was produced AFTER filterCommonGenes; scoring the raw
    # 17,256-gene matrix divides ranks by the wrong gene count.
    expression = filter_common_genes(raw, load_common_genes(ESTIMATE_TARBALL))
    assert len(expression) < len(raw)

    ours = estimate_scores(expression, signatures)

    np.testing.assert_allclose(
        ours["StromalScore"].to_numpy(),
        reference.loc["Stromal141_UP"].to_numpy(dtype=float),
        rtol=1e-6,
        err_msg="stromal score diverges from the reference implementation",
    )
    np.testing.assert_allclose(
        ours["ImmuneScore"].to_numpy(),
        reference.loc["Immune141_UP"].to_numpy(dtype=float),
        rtol=1e-6,
        err_msg="immune score diverges from the reference implementation",
    )
    np.testing.assert_allclose(
        ours["ESTIMATEScore"].to_numpy(),
        reference.loc["ESTIMATE"].to_numpy(dtype=float),
        rtol=1e-6,
    )


@needs_package
def test_the_shipped_purity_example_is_stale_relative_to_the_source():
    """The package's own sample_purity.gct does NOT match its own code.

    Both fixtures carry an identical ESTIMATE row, so purity should be a
    deterministic function of a number we already reproduce exactly. It is not.
    Solving cos-inverse back through the fixture gives

        intercept 0.6036365441, slope 0.0001506451

    against the ``estimateScore.R`` v1.0.13 source values

        intercept 0.6049872018, slope 0.0001467884

    with a linear-fit residual of 8e-16 — machine precision. So the shipped
    example was generated by an earlier version of the conversion and never
    regenerated. **We follow the source, not the stale example**, and the
    remaining disagreement is at most ~0.015 in purity units.

    This test pins the discrepancy rather than hiding it behind a loose
    tolerance. If a future ESTIMATE release regenerates the example, this test
    fails and someone re-reads the constants — which is the correct outcome.
    """
    purity_gct = _read_gct(_member("inst/extdata/sample_purity.gct"))
    expression = filter_common_genes(
        _read_gct(_member("inst/extdata/sample_input.gct")),
        load_common_genes(ESTIMATE_TARBALL),
    )
    signatures = load_signatures(ESTIMATE_TARBALL)
    scores = estimate_scores(expression, signatures)["ESTIMATEScore"]

    reference = purity_gct.loc["ESTIMATE-predicted tumor purity"].to_numpy(dtype=float)

    # We match the source formula exactly.
    ours = affymetrix_purity(scores).to_numpy(dtype=float)
    np.testing.assert_allclose(
        ours, np.cos(AFFY_PURITY_INTERCEPT + AFFY_PURITY_SLOPE * scores.to_numpy()), rtol=1e-12
    )

    # And the fixture is exactly reproducible with the older constants, which is
    # what proves the machinery is right and only the constants moved.
    stale = np.cos(0.6036365441 + 0.0001506451 * scores.to_numpy())
    np.testing.assert_allclose(stale, reference, atol=1e-9)

    # The practical size of the disagreement, stated rather than assumed.
    assert np.abs(ours - reference).max() < 0.02


