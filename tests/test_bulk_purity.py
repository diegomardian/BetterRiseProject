def test_duplicate_symbols_collapse_to_the_dominant_transcript():
    expr = pd.DataFrame(
        {"E1": [100.0, 120.0], "E2": [1.0, 2.0], "E3": [7.0, 9.0]},
        index=["S0", "S1"],
    )
    gene_map = pd.DataFrame(
        {"ensembl_id": ["E1", "E2", "E3"], "gene_symbol": ["AAA", "AAA", "BBB"]}
    )
    out, counts = to_symbol_matrix(expr, gene_map, ["AAA", "BBB"])
    assert list(out.index) == ["AAA", "BBB"]
    assert out.loc["AAA", "S0"] == 100.0  # E1 wins, E2 dropped — not summed to 101
    assert counts["unique_symbols"] == 2


def test_symbol_mapping_reports_loss_at_each_step():
    expr = pd.DataFrame({"E1": [1.0], "E_unmapped": [2.0]}, index=["S0"])
    gene_map = pd.DataFrame({"ensembl_id": ["E1"], "gene_symbol": ["AAA"]})
    _, counts = to_symbol_matrix(expr, gene_map, ["AAA", "ZZZ"])
    assert counts["ensembl_in_matrix"] == 2
    assert counts["mapped_to_a_symbol"] == 1
    assert counts["in_estimate_common_genes"] == 1
    assert counts["common_genes_total"] == 2


def _manifest(barcodes):
    return pd.DataFrame(
        {
            "barcode": barcodes,
            "patient_id": [b[:12] for b in barcodes],
            "project": ["TCGA-COAD"] * len(barcodes),
            "sample_type": ["01"] * len(barcodes),
            "sample_type_name": ["primary_tumour"] * len(barcodes),
        }
    ).set_index("barcode")


def test_the_two_methods_are_never_coalesced():
    """The brief: 'do not silently coalesce the two'. One row per (sample,
    method), so ABSOLUTE's coverage gap stays visible instead of being
    backfilled with an expression-derived number."""
    barcodes = ["TCGA-AA-0000-01A-01R-1410-07", "TCGA-AA-0001-01A-01R-1410-07"]
    scores = pd.DataFrame(
        {"StromalScore": [10.0, 20.0], "ImmuneScore": [5.0, 6.0], "ESTIMATEScore": [15.0, 26.0]},
        index=pd.Index(barcodes, name="barcode"),
    )
    # ABSOLUTE is keyed at sample level — it is called from a DNA aliquot that
    # never shares a barcode with our RNA aliquot.
    absolute = pd.DataFrame(
        {
            "sample_key": ["TCGA-AA-0000-01A"],
            "cancer_type": ["COAD"],
            "aran_absolute": [0.7],
            "aran_estimate": [0.8],
            "aran_cpe": [0.75],
        }
    )
    table = assemble_purity_table(scores, absolute, manifest=_manifest(barcodes))

    assert set(table["method"]) == {"estimate_affy_extrapolated", "absolute", "aran_cpe"}
    assert len(table) == 4  # two ESTIMATE rows, one ABSOLUTE, one CPE
    matched = table[table["barcode"] == barcodes[0]]
    assert set(matched["method"]) == {"estimate_affy_extrapolated", "absolute", "aran_cpe"}
    # The unmatched sample keeps its ESTIMATE row and gains nothing else — the
    # coverage gap stays visible rather than being backfilled.
    assert table[table["barcode"] == barcodes[1]]["method"].tolist() == [
        "estimate_affy_extrapolated"
    ]
    assert table.loc[table["method"] == "absolute", "expression_derived"].eq(False).all()
    assert table.loc[
        table["method"] == "estimate_affy_extrapolated", "expression_derived"
    ].all()


def test_sample_key_bridges_the_dna_rna_aliquot_gap():
    from src.bulk.purity import sample_key

    assert sample_key("TCGA-A6-2670-01A-01R-1410-07") == "TCGA-A6-2670-01A"
    # A DNA aliquot of the same sample maps to the same key. That is the point.
    assert sample_key("TCGA-A6-2670-01A-11D-A29H-01") == "TCGA-A6-2670-01A"


def test_agreement_reports_coverage_even_with_no_absolute():
    scores = pd.DataFrame(
        {"StromalScore": [10.0], "ImmuneScore": [5.0], "ESTIMATEScore": [15.0]},
        index=pd.Index(["TCGA-AA-0000-01A"], name="barcode"),
    )
    table = assemble_purity_table(scores, None, manifest=_manifest(list(scores.index)))
    stats = agreement(table)
    assert stats["n_absolute"] == 0
    assert stats["absolute_coverage"] == 0.0
    assert "pearson_r" not in stats
