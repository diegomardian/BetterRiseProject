def _toy(n_genes=400, n_samples=6, seed=0):
    rng = np.random.default_rng(seed)
    genes = [f"G{i}" for i in range(n_genes)]
    return pd.DataFrame(
        rng.lognormal(3, 1, (n_genes, n_samples)),
        index=genes,
        columns=[f"S{j}" for j in range(n_samples)],
    )


def _toy_signatures(expr):
    genes = list(expr.index)
    return {"StromalSignature": genes[:50], "ImmuneSignature": genes[50:100]}


def test_scale_invariance_tpm_and_log_agree_exactly():
    """The first step is a per-sample rank, so any monotone transform gives the
    same answer. Worth pinning: it means W3.3 is immune to the TPM/log2-CPM
    mix-up that the rest of the pipeline asserts against."""
    expr = _toy()
    sigs = _toy_signatures(expr)
    linear = estimate_scores(expr, sigs)
    logged = estimate_scores(np.log2(expr + 1), sigs)
    pd.testing.assert_frame_equal(linear, logged)


def test_stromal_signal_raises_the_stromal_score():
    """A positive control. Inflate the stromal genes and the score must move."""
    expr = _toy()
    sigs = _toy_signatures(expr)
    base = estimate_scores(expr, sigs)
    spiked = expr.copy()
    spiked.loc[sigs["StromalSignature"], "S0"] *= 50
    after = estimate_scores(spiked, sigs)
    assert after.loc["S0", "StromalScore"] > base.loc["S0", "StromalScore"]
    assert after.loc["S1", "StromalScore"] == pytest.approx(base.loc["S1", "StromalScore"])


def test_estimate_score_is_the_sum_of_the_two():
    scores = estimate_scores(_toy(), _toy_signatures(_toy()))
    np.testing.assert_allclose(
        scores["ESTIMATEScore"], scores["StromalScore"] + scores["ImmuneScore"]
    )


def test_no_purity_column_is_emitted_by_default():
    """The purity conversion is Affymetrix-only in the original. It has to be
    asked for explicitly, and it is not called 'purity'."""
    scores = estimate_scores(_toy(), _toy_signatures(_toy()))
    assert "TumorPurity" not in scores.columns
    assert not any("purity" in c.lower() for c in scores.columns)


def test_affy_purity_matches_the_published_formula():
    s = pd.Series([0.0, 1000.0, -2000.0])
    expected = np.cos(AFFY_PURITY_INTERCEPT + AFFY_PURITY_SLOPE * s)
    np.testing.assert_allclose(affymetrix_purity(s).to_numpy(), expected.to_numpy())


def test_affy_purity_nulls_out_of_range_values():
    """estimateScore.R sets negative purities to NA rather than clipping."""
    huge = pd.Series([50000.0])
    assert affymetrix_purity(huge).isna().all()


