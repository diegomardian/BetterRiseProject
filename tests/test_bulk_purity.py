"""W3.3 — does our ESTIMATE reproduce the real ESTIMATE?

`src/bulk/purity.py` reimplements a GPL-2 R package because R does not run
here. A reimplementation that quietly differs from the canonical tool is worse
than no tool at all, so the load-bearing test in this file is
:func:`test_reproduces_the_packages_own_reference_output` — the ESTIMATE
package ships ``sample_input.gct`` together with the ``sample_estimate.gct`` it
produces from it, and we assert we match those numbers.

If that test passes, this is ESTIMATE. If it fails, nothing else here matters.

The fixture is downloaded rather than committed: it is someone else's GPL-2
material and vendoring it raises a licensing question for no benefit. Tests
that need it skip when it is absent, so CI stays green offline.
"""

from __future__ import annotations

import io
import tarfile

import numpy as np
import pandas as pd
import pytest

from src.bulk.purity import (
    AFFY_PURITY_INTERCEPT,
    AFFY_PURITY_SLOPE,
    PurityError,
    affymetrix_purity,
    agreement,
    assemble_purity_table,
    estimate_scores,
    filter_common_genes,
    load_common_genes,
    load_signatures,
    to_symbol_matrix,
)
from src.common.paths import RAW_DIR

ESTIMATE_TARBALL = RAW_DIR / "estimate" / "estimate_1.0.13.tar.gz"
needs_package = pytest.mark.skipif(
    not ESTIMATE_TARBALL.exists(),
    reason="ESTIMATE source not downloaded; run `python -m src.bulk.run_purity fetch`",
)


def _read_gct(text: str) -> pd.DataFrame:
    """GCT: two header lines, then Name/Description/samples..."""
    df = pd.read_csv(io.StringIO(text), sep="\t", skiprows=2, index_col=0)
    return df.drop(columns=[df.columns[0]])


def _member(suffix: str) -> str:
    with tarfile.open(ESTIMATE_TARBALL, "r:gz") as tf:
        for m in tf.getmembers():
            if m.name.endswith(suffix):
                return tf.extractfile(m).read().decode("utf-8")
    raise AssertionError(f"{suffix} missing")


